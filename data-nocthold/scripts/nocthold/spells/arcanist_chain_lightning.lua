-- Nocthold | Arcanist: Chain Lightning.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local combat = Combat()
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_ENERGYDAMAGE)
combat:setParameter(COMBAT_PARAM_EFFECT, CONST_ME_ENERGYHIT)
combat:setFormula(COMBAT_FORMULA_LEVELMAGIC, -0.45, -10, -0.65, -18)
combat:setArea(createCombatArea(AREA_CIRCLE2X2))

local spell = Spell("instant")
spell:name("Chain Lightning")
spell:words("nocthold chain")
spell:group("attack")
spell:cooldown(18000)
spell:groupCooldown(1000)
spell:level(20)
spell:mana(68)
spell:needTarget(true)
spell:range(6)
spell:blockWalls(true)
spell:isAggressive(true)
spell:needLearn(false)
spell:vocation("sorcerer;true", "master sorcerer;true")
spell:onCastSpell(function(creature, variant)
    return combat:execute(creature, variant)
end)
spell:register()
Nocthold.registerSpell("Chain Lightning")
