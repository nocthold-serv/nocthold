-- Nocthold | Arcanist: Arcane Surge.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local spell = Spell("instant")
spell:name("Arcane Surge")
spell:words("aeth celer")
spell:id(1030)
spell:group("support")
spell:cooldown(30000)
spell:groupCooldown(1000)
spell:level(12)
spell:mana(42)
spell:needTarget(false)
spell:isSelfTarget(true)
spell:allowOnSelf(true)
spell:isAggressive(false)
spell:needLearn(false)
spell:vocation("sorcerer;true", "master sorcerer;true")
spell:onCastSpell(function(creature, variant)
    local condition = Condition(CONDITION_HASTE)
    condition:setParameter(CONDITION_PARAM_TICKS, 6000)
    condition:setParameter(CONDITION_PARAM_SPEED, 80)
    creature:addCondition(condition)
    creature:getPosition():sendMagicEffect(CONST_ME_MAGIC_BLUE)
    return true
end)
spell:register()
Nocthold.registerSpell("Arcane Surge")
