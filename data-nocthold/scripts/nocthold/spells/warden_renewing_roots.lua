-- Nocthold
-- Applies 4 regeneration ticks over 8 seconds to one friendly target.

local combat = Combat()
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_HEALING)
combat:setParameter(COMBAT_PARAM_EFFECT, CONST_ME_MAGIC_GREEN)
combat:setParameter(COMBAT_PARAM_AGGRESSIVE, false)
combat:setFormula(COMBAT_FORMULA_LEVELMAGIC, 0.15, 5, 0.20, 8)

local regeneration = Condition(CONDITION_REGENERATION)
regeneration:setParameter(CONDITION_PARAM_TICKS, 8000)
regeneration:setParameter(CONDITION_PARAM_HEALTHGAIN, 35)
regeneration:setParameter(CONDITION_PARAM_HEALTHTICKS, 2000)
combat:addCondition(regeneration)

local spell = Spell("instant")
spell:name("Renewing Roots")
spell:words("sylva rhun")
spell:id(1012)
spell:group("healing")
spell:cooldown(10000)
spell:groupCooldown(1000)
spell:level(4)
spell:mana(28)
spell:needTarget(true)
spell:range(5)
spell:allowOnSelf(true)
spell:isAggressive(false)
spell:needLearn(false)
spell:vocation("druid;true", "elder druid;true")
spell:onCastSpell(function(creature, variant)
    return combat:execute(creature, variant)
end)
spell:register()
Nocthold.registerSpell("Renewing Roots")
