-- Nocthold | Warden: Lifebloom.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local spell = Spell("instant")
spell:name("Lifebloom")
spell:words("nocthold lifebloom")
spell:group("healing")
spell:cooldown(18000)
spell:groupCooldown(1000)
spell:level(10)
spell:mana(36)
spell:needTarget(true)
spell:range(5)
spell:allowOnSelf(true)
spell:isAggressive(false)
spell:needLearn(false)
spell:vocation("druid;true", "elder druid;true")
spell:onCastSpell(function(creature, variant)
    local condition = Condition(CONDITION_REGENERATION)
    condition:setParameter(CONDITION_PARAM_TICKS, 10000)
    condition:setParameter(CONDITION_PARAM_HEALTHGAIN, 45)
    condition:setParameter(CONDITION_PARAM_HEALTHTICKS, 2000)
    local targetCreature = Creature(variant:getNumber())
    if not targetCreature then return false end
    targetCreature:addCondition(condition)
    targetCreature:getPosition():sendMagicEffect(CONST_ME_MAGIC_GREEN)
    return true
end)
spell:register()
Nocthold.registerSpell("Lifebloom")
