-- Nocthold | Arcanist: Shatter.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local combat = Combat()
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_ICEDAMAGE)
combat:setParameter(COMBAT_PARAM_EFFECT, CONST_ME_ICEATTACK)
combat:setFormula(COMBAT_FORMULA_LEVELMAGIC, -0.72, -10, -0.95, -16)

local spell = Spell("instant")
spell:name("Shatter")
spell:words("aeth krys")
spell:id(1022)
spell:group("attack")
spell:cooldown(8500)
spell:groupCooldown(1000)
spell:level(6)
spell:mana(24)
spell:needTarget(true)
spell:range(6)
spell:blockWalls(true)
spell:isAggressive(true)
spell:needLearn(false)
spell:vocation("sorcerer;true", "master sorcerer;true")
spell:onCastSpell(function(creature, variant)
    return combat:execute(creature, variant)
end)
spell:register()
Nocthold.registerSpell("Shatter")
