-- Nocthold | Guardian: Guardian's Oath.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local spell = Spell("instant")
spell:name("Guardian's Oath")
spell:words("stal oth")
spell:id(1010)
spell:group("support")
spell:cooldown(90000)
spell:groupCooldown(1000)
spell:level(20)
spell:mana(55)
spell:needTarget(false)
spell:isSelfTarget(true)
spell:allowOnSelf(true)
spell:isAggressive(false)
spell:needLearn(false)
spell:vocation("knight;true", "elite knight;true")
spell:onCastSpell(function(creature, variant)
    local condition = Condition(CONDITION_ATTRIBUTES)
    condition:setParameter(CONDITION_PARAM_TICKS, 8000)
    condition:setParameter(CONDITION_PARAM_STAT_MAXHITPOINTSPERCENT, 110)
    creature:addCondition(condition)
    creature:getPosition():sendMagicEffect(CONST_ME_HOLYDAMAGE)
    return true
end)
spell:register()
Nocthold.registerSpell("Guardian's Oath")
