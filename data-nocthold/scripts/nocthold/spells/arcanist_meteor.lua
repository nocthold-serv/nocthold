-- Nocthold | Arcanist: Meteor.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local combat = Combat()
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_FIREDAMAGE)
combat:setParameter(COMBAT_PARAM_EFFECT, CONST_ME_FIREAREA)
combat:setFormula(COMBAT_FORMULA_LEVELMAGIC, -0.6, -15, -0.85, -25)
combat:setArea(createCombatArea(AREA_CIRCLE2X2))

local spell = Spell("instant")
spell:name("Meteor")
spell:words("nocthold meteor")
spell:group("attack")
spell:cooldown(22000)
spell:groupCooldown(1000)
spell:level(16)
spell:mana(58)
spell:needTarget(true)
spell:range(6)
spell:blockWalls(true)
spell:isAggressive(true)
spell:needLearn(false)
spell:vocation("sorcerer;true", "master sorcerer;true")
spell:onCastSpell(function(creature, variant)
    return combat:execute(creature, variant)
end)
spell:register()
Nocthold.registerSpell("Meteor")
