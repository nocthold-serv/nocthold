-- Nocthold | Warden: Thorn Lash.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local combat = Combat()
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_EARTHDAMAGE)
combat:setParameter(COMBAT_PARAM_EFFECT, CONST_ME_SMALLPLANTS)
combat:setFormula(COMBAT_FORMULA_LEVELMAGIC, -0.6, -8, -0.85, -14)

local spell = Spell("instant")
spell:name("Thorn Lash")
spell:words("ronce vas")
spell:id(1018)
spell:group("attack")
spell:cooldown(7000)
spell:groupCooldown(1000)
spell:level(6)
spell:mana(26)
spell:needTarget(true)
spell:range(5)
spell:blockWalls(true)
spell:isAggressive(true)
spell:needLearn(false)
spell:vocation("druid;true", "elder druid;true")
spell:onCastSpell(function(creature, variant)
    return combat:execute(creature, variant)
end)
spell:register()
Nocthold.registerSpell("Thorn Lash")
