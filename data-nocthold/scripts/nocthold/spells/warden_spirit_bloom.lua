-- Nocthold | Warden: Spirit Bloom.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local combat = Combat()
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_HEALING)
combat:setParameter(COMBAT_PARAM_EFFECT, CONST_ME_HOLYDAMAGE)
combat:setParameter(COMBAT_PARAM_AGGRESSIVE, false)
combat:setFormula(COMBAT_FORMULA_LEVELMAGIC, 0.45, 12, 0.7, 20)
combat:setArea(createCombatArea(AREA_CIRCLE2X2))

local spell = Spell("instant")
spell:name("Spirit Bloom")
spell:words("sylva anim")
spell:id(1016)
spell:group("healing")
spell:cooldown(25000)
spell:groupCooldown(1000)
spell:level(16)
spell:mana(45)
spell:needTarget(true)
spell:range(5)
spell:allowOnSelf(true)
spell:isAggressive(false)
spell:needLearn(false)
spell:vocation("druid;true", "elder druid;true")
spell:onCastSpell(function(creature, variant)
    return combat:execute(creature, variant)
end)
spell:register()
Nocthold.registerSpell("Spirit Bloom")
