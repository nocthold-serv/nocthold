-- Nocthold | Guardian: Iron Sweep.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local combat = Combat()
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_PHYSICALDAMAGE)
combat:setParameter(COMBAT_PARAM_EFFECT, CONST_ME_HITAREA)
combat:setFormula(COMBAT_FORMULA_LEVELMAGIC, -0.3, -6, -0.48, -12)
combat:setArea(createCombatArea(AREA_CIRCLE2X2))

local spell = Spell("instant")
spell:name("Iron Sweep")
spell:words("nocthold sweep")
spell:group("attack")
spell:cooldown(12000)
spell:groupCooldown(1000)
spell:level(10)
spell:mana(28)
spell:needTarget(true)
spell:range(5)
spell:blockWalls(true)
spell:isAggressive(true)
spell:needLearn(false)
spell:vocation("knight;true", "elite knight;true")
spell:onCastSpell(function(creature, variant)
    return combat:execute(creature, variant)
end)
spell:register()
Nocthold.registerSpell("Iron Sweep")
