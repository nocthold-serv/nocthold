-- Nocthold | Warden: Nature's Grasp.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local combat = Combat()
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_ICEDAMAGE)
combat:setParameter(COMBAT_PARAM_EFFECT, CONST_ME_GREEN_RINGS)
combat:setFormula(COMBAT_FORMULA_LEVELMAGIC, -0.25, -4, -0.35, -8)
local slow = Condition(CONDITION_PARALYZE)
slow:setParameter(CONDITION_PARAM_TICKS, 3000)
slow:setParameter(CONDITION_PARAM_SPEED, -70)
combat:addCondition(slow)

local spell = Spell("instant")
spell:name("Nature's Grasp")
spell:words("ronce tenn")
spell:id(1019)
spell:group("attack")
spell:cooldown(18000)
spell:groupCooldown(1000)
spell:level(12)
spell:mana(38)
spell:needTarget(true)
spell:range(5)
spell:blockWalls(true)
spell:isAggressive(true)
spell:needLearn(false)
spell:vocation("druid;true", "elder druid;true")
spell:onCastSpell(function(creature, variant)
    return combat:execute(creature, variant)
end)
spell:register()
Nocthold.registerSpell("Nature's Grasp")
