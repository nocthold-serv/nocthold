-- Nocthold | Arcanist: Mana Ward.
-- Canary 3.6.1 Revscriptsys; values are first-pass balance and require in-game tuning.
local spell = Spell("instant")
spell:name("Mana Ward")
spell:words("aeth custos")
spell:id(1029)
spell:group("support")
spell:cooldown(30000)
spell:groupCooldown(1000)
spell:level(10)
spell:mana(40)
spell:needTarget(false)
spell:isSelfTarget(true)
spell:allowOnSelf(true)
spell:isAggressive(false)
spell:needLearn(false)
spell:vocation("sorcerer;true", "master sorcerer;true")
spell:onCastSpell(function(creature, variant)
    local condition = Condition(CONDITION_ATTRIBUTES)
    condition:setParameter(CONDITION_PARAM_TICKS, 7000)
    condition:setParameter(CONDITION_PARAM_SKILL_SHIELDPERCENT, 130)
    creature:addCondition(condition)
    creature:getPosition():sendMagicEffect(CONST_ME_ENERGYHIT)
    return true
end)
spell:register()
Nocthold.registerSpell("Mana Ward")
